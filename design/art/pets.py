def render(name):
    shape, pal = P[name]
    rows = S[shape].strip("\n").split("\n")
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    top = 16 - len(rows)  # 바닥에 붙여서(펫이 땅에 서 있게)
    for y, r in enumerate(rows):
        for x, c in enumerate(r[:16]):
            if c != ".":
                im.putpixel((x, top + y), pal[c])
    im.save(os.path.join(OUT, name + ".png"))

for name in P:
    render(name)
