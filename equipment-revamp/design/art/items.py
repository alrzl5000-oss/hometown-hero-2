def render(shape, pal, path):
    rows = [r for r in S[shape].strip("\n").split("\n")]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    top = (16 - len(rows)) // 2
    cols = {"K": K, "A": hx(pal[0]), "B": hx(pal[1]), "C": hx(pal[2]), "D": hx(pal[3]), "E": hx(pal[4])}
    for y, r in enumerate(rows):
        for x, c in enumerate(r[:16]):
            if c != ".":
                im.putpixel((x, top + y), cols[c])
    im.save(path)

n = 0
